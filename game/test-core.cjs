const assert=require('node:assert/strict');
const K=require('./core.js');
const config={startMap:'school',worldWidth:1920,worldHeight:1280,dayLengthSeconds:720};
const s=K.fresh();
assert.equal(K.plotAction(s,0,'water').ok,false);
assert.equal(K.plotAction(s,0,'seed').ok,true);
assert.equal(s.seeds,11);
assert.equal(K.plotAction(s,0,'seed').ok,false);
K.grow(s,100,18);assert.equal(s.plots[0].stage,1,'dry seeds cannot grow');
K.plotAction(s,0,'water');K.grow(s,17,18);assert.equal(s.plots[0].stage,1);
K.grow(s,1,18);assert.equal(s.plots[0].stage,2);
K.plotAction(s,0,'hand');assert.equal(s.crops,1);assert.equal(s.plots[0].stage,0);
assert.equal(K.sell(s,12),12);assert.equal(s.coins,42);assert.equal(K.sell(s,12),0);
assert.equal(K.buySeeds(s),true);assert.equal(s.coins,32);assert.equal(s.seeds,16);
const noCash=K.fresh();noCash.coins=0;assert.equal(K.buySeeds(noCash),false);
assert.equal(K.complete(s,'plant'),false,'quest rewards should not repeat');
const p={x:50,y:100},q={...p};K.move(p,1,0,.1,100,[],500,500);K.move(q,1,1,.1,100,[],500,500);
assert.ok(Math.abs(Math.hypot(q.x-50,q.y-100)-10)<.0001,'diagonal speed normalized');
const blocked={x:50,y:100};K.move(blocked,1,0,1,300,[{x:80,y:50,w:10,h:100}],500,500);assert.ok(blocked.x<69,'no tunneling');
const loaded=K.restore(JSON.parse(JSON.stringify(s)),config);assert.equal(loaded.coins,s.coins);assert.equal(loaded.quests.sell,true);
const corrupt=K.restore({version:1,coins:-900,map:'bad',plots:[null]},config);assert.equal(corrupt.coins,0);assert.equal(corrupt.map,'school');assert.equal(corrupt.plots.length,9);
assert.deepEqual(Object.keys(K.SEASONS),['spring','summer','autumn','winter']);
const fishing=K.fresh('farm');
assert.equal(K.castLine(fishing),true);
assert.equal(K.catchFish(fishing,.95),'sunset_koi');
const resumed=K.restore(JSON.parse(JSON.stringify(fishing)),config);
assert.equal(resumed.bait,5);
assert.equal(resumed.fish.sunset_koi,1);
assert.equal(K.sellFish(resumed),30);
assert.equal(K.sellFish(resumed),0);
resumed.bait=0;
assert.equal(K.castLine(resumed),false);
assert.equal(K.buyBait(resumed),true);
assert.equal(resumed.bait,5);
console.log('PASS: crop loop, economy, quests, normalized movement, collision, save validation, 4 seasons');
